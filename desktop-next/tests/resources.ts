import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parse } from 'yaml';
import { ExpertLibrary } from '../electron/expert-library';
import { ResourceStore } from '../electron/resources';

const root = path.resolve(process.argv[2]);
const output = path.resolve(process.argv[3]);
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'soul-resource-验收-'));
let library = new ExpertLibrary(root, profile);
let store = new ResourceStore(root, profile, library);
const checks: string[] = [];
const check = (title: string, test: () => void) => { const started = Date.now(); test(); checks.push(title); console.log(`${title}: ${Date.now() - started} ms`); };
const sourceMemory = fs.readFileSync(path.join(root, 'expert-packs/finance-expert/memory/MEMORY.md'), 'utf8');
const sourceSoul = fs.readFileSync(path.join(root, 'expert-packs/finance-expert/soul.md'), 'utf8');
const sourceIndex = fs.readFileSync(path.join(root, 'expert-packs/finance-expert/skills/skill-index.yaml'), 'utf8');
let collectionId = '';
try {
  check('Resource lists and file previews use real packs; viewing never installs or modifies a source', () => {
    const snapshot = store.read('finance-expert');
    assert.equal(snapshot.memory!.content, sourceMemory);
    assert.equal(snapshot.settings!.content, sourceSoul);
    assert.equal(snapshot.collections.length, 11);
    assert.equal(snapshot.skills.filter(skill => skill.configured).length, library.detail('finance-expert').skills.length);
    assert.throws(() => store.saveMemory('finance-expert', '不应落盘', snapshot.memory!.revision, '用户偏好'), /先安装/);
    assert(!library.detail('finance-expert').installed);
    assert.equal(store.readDocument('expert:finance-expert', 'README.md', '').content, fs.readFileSync(path.join(root, 'expert-packs/finance-expert/knowledge/README.md'), 'utf8'));
    library.installExpert('finance-expert'); library.installExpert('hr-expert');
  });
  check('Projects validate existing directories and keep each expert private scope isolated', () => {
    const project = { id: '', name: '公开验收项目', description: '', expertId: '', sources: [{ type: 'local' as const, path: profile }], updated: '' };
    store.saveProject(project, '');
    store.saveProject({ ...project, name: '财研私密项目', expertId: 'finance-expert' }, 'finance-expert');
    assert.equal(store.read('').projects.length, 1);
    assert.equal(store.read('finance-expert').projects.length, 2);
    assert.equal(store.read('hr-expert').projects.length, 1);
    assert.throws(() => store.saveProject({ ...project, name: '无效路径', sources: [{ type: 'local', path: path.join(profile, 'missing') }] }, ''));
    assert.throws(() => store.saveProject({ ...project, sources: [project.sources[0], project.sources[0]] }, ''), /重复/);
    assert.throws(() => store.saveProject({ ...project, sources: [{ type: 'git', path: 'https://user:pass@example.com/repo.git' }] }, ''), /凭据/);
    const privateProject = store.read('finance-expert').projects.find(item => item.expertId)!;
    assert.throws(() => store.removeProject(privateProject.id, 'hr-expert'), /不存在/);
    store.removeProject(privateProject.id, 'finance-expert'); store.restoreTrash('finance-expert');
    assert.equal(store.read('finance-expert').projects.length, 2);
  });
  check('Knowledge bindings persist in avatar.config and do not grant another expert implicit access', () => {
    store.saveCollection('', '验收资料库');
    collectionId = store.read('').collections.find(item => !item.builtin)!.id;
    store.saveDocument({ collectionId, id: '', name: '验收.md', content: '# 真实资料\n<script>never execute</script>\n原始证据', revision: '' }, '');
    assert.throws(() => store.documents(collectionId, 'finance-expert'), /未绑定/);
    store.bind('finance-expert', [...store.read('finance-expert').bindings, collectionId]);
    assert.equal(store.documents(collectionId, 'finance-expert').length, 1);
    assert.throws(() => store.documents(collectionId, 'hr-expert'), /未绑定/);
    const config = JSON.parse(fs.readFileSync(path.join(profile, 'avatars/finance-expert/avatar.config.json'), 'utf8'));
    assert(config.knowledgeCollections.includes(collectionId));
    assert.throws(() => store.saveDocument({ collectionId: 'expert:hr-expert', id: '', name: '越界.md', content: '不应保存', revision: '' }, 'finance-expert'));
  });
  check('Document edits reject stale revisions and removals can be restored without losing original content', () => {
    const file = store.documents(collectionId, '')[0];
    const original = store.readDocument(collectionId, file.id, '');
    store.saveDocument({ collectionId, id: file.id, name: file.name, content: original.content + '\n新资料', revision: original.revision }, '');
    assert.throws(() => store.saveDocument({ collectionId, id: file.id, name: file.name, content: '旧窗口不应覆盖', revision: original.revision }, ''), /已变更/);
    const current = store.readDocument(collectionId, file.id, '');
    store.removeDocument(collectionId, file.id, current.revision, '');
    assert.equal(store.documents(collectionId, '').length, 0);
    store.restoreTrash('');
    assert.equal(store.readDocument(collectionId, file.id, '').content, current.content);
    assert.throws(() => store.saveDocument({ collectionId, id: '', name: '../escape.md', content: 'no', revision: '' }, ''));
    assert.throws(() => store.readDocument(collectionId, '../../soul.sqlite', ''));
    store.removeCollection(collectionId); assert(!store.read('').collections.some(item => item.id === collectionId));
    store.restoreTrash(''); assert.equal(store.documents(collectionId, '').length, 1);
  });
  check('Grouped memory edits preserve the original preamble and extra chapters; restoration creates a new version', () => {
    let memory = store.read('finance-expert').memory!;
    const original = memory.content;
    store.saveMemory('finance-expert', '用户确认：简洁回复。', memory.revision, '用户偏好');
    memory = store.read('finance-expert').memory!;
    assert(memory.content.startsWith(original));
    assert(memory.content.includes('## 纠偏记录'));
    assert.equal(store.read('hr-expert').memory!.content, fs.readFileSync(path.join(root, 'expert-packs/hr-expert/memory/MEMORY.md'), 'utf8'));
    assert.throws(() => store.saveMemory('finance-expert', '旧编辑', 'stale', '用户偏好'), /已变更/);
    assert.throws(() => store.saveMemory('finance-expert', memory.content.replace('## 用户偏好', '## 删除'), memory.revision, ''), /请保留/);
    assert.throws(() => store.saveMemory('finance-expert', memory.content + '\n## 用户偏好\n重复', memory.revision, ''), /请保留/);
    const versions = store.read('finance-expert').versions;
    store.restoreVersion('finance-expert', versions.find(item => item.reason === '原始文件')!.id, memory.revision);
    assert.equal(store.read('finance-expert').memory!.content, original);
    assert.equal(store.read('finance-expert').versions.length, 3);
    assert.throws(() => store.restoreVersion('hr-expert', versions[0].id, store.read('hr-expert').memory!.revision), /不存在/);
  });
  check('Skill changes respect local priority and retain unrelated routing metadata and shared source files', () => {
    const before = parse(sourceIndex);
    const otherExpertSkills = library.detail('hr-expert').skills;
    const candidate = store.read('finance-expert').skills.find(skill => !skill.configured && skill.source === 'shared')!;
    assert(candidate);
    store.configureSkill('finance-expert', candidate.key, true);
    assert(library.detail('finance-expert').skills.some(skill => skill.name === candidate.name));
    store.configureSkill('finance-expert', candidate.key, false);
    assert(!library.detail('finance-expert').skills.some(skill => skill.name === candidate.name));
    const next = parse(fs.readFileSync(path.join(profile, 'avatars/finance-expert/skills/skill-index.yaml'), 'utf8'));
    assert.deepEqual(next.shared_skills.find((skill: any) => skill.name === 'agent-reach'), before.shared_skills.find((skill: any) => skill.name === 'agent-reach'));
    const content = '---\nname: draw-chart\ndescription: 用户上传的专属覆写\n---\n# 用户技能\n原始内容';
    store.uploadSkill('finance-expert', content);
    assert.equal(library.detail('finance-expert').skills.find(skill => skill.name === 'draw-chart')!.source, 'local');
    assert.equal(store.readSkill('finance-expert', 'local:skills/draw-chart.md').content, content);
    assert.deepEqual(library.detail('hr-expert').skills, otherExpertSkills);
    assert.throws(() => store.uploadSkill('finance-expert', '---\nname: ../escape\ndescription: no\n---\nx'));
    assert.throws(() => store.uploadSkill('finance-expert', '---\nname: invalid\ndescription: |\n  first\n  second\n---\nx'), /单行/);
    assert.throws(() => store.uploadSkill('finance-expert', '---\nname: oversize\ndescription: no\n---\n' + '中'.repeat(30000)), /64 KB/);
    assert.throws(() => store.readSkill('finance-expert', 'shared:../../soul.sqlite'));
  });
  check('Settings update the real independent configuration, reject duplicates and retain operation rules', () => {
    const agents = fs.readFileSync(path.join(profile, 'avatars/finance-expert/AGENTS.md'), 'utf8');
    const snapshot = library.saveSettings('finance-expert', '验收财研', '用户保存的简介', '用户模型偏好');
    assert.equal(snapshot.experts.find(item => item.id === 'finance-expert')!.defaultModel, '用户模型偏好');
    assert.equal(library.detail('finance-expert').description, '用户保存的简介');
    assert.throws(() => library.saveSettings('finance-expert', library.detail('hr-expert').name, '', 'Auto'), /已存在/);
    const soul = store.read('finance-expert').settings!;
    store.saveSoul('finance-expert', soul.content + '\n## 用户确认的补充\n保留专业来源。\n', soul.revision);
    assert.equal(fs.readFileSync(path.join(profile, 'avatars/finance-expert/AGENTS.md'), 'utf8'), agents);
    assert.throws(() => store.saveSoul('finance-expert', '坏文件', soul.revision), /标题/);
  });
  check('Quality reports inspect real files and leave professional model tests explicitly unexecuted', () => {
    const quality = store.checkQuality('finance-expert');
    assert.equal(quality.professional, '未执行');
    assert.equal(quality.cases.length, library.detail('finance-expert').testCases);
    assert(quality.cases.length >= 5);
    assert.equal(store.readCase('finance-expert', quality.cases[0].id).content, fs.readFileSync(path.join(profile, 'avatars/finance-expert/tests/cases', quality.cases[0].id), 'utf8'));
    assert.throws(() => store.readCase('finance-expert', '../../soul.md'));
    const xiaodu = store.checkQuality('小堵-工商储专家');
    assert.equal(xiaodu.checks.find(item => item.name === '至少 5 个专业测试用例')!.ok, xiaodu.cases.length >= 5);
  });
  check('Restart restores bindings, projects, skills, memory history and edited settings; bundled sources stay exact', () => {
    const previous = store.read('finance-expert');
    store.close(); library.close(); library = new ExpertLibrary(root, profile); store = new ResourceStore(root, profile, library);
    const next = store.read('finance-expert');
    assert.deepEqual(next.bindings, previous.bindings);
    assert.deepEqual(next.projects, previous.projects);
    assert.deepEqual(next.versions, previous.versions);
    assert.equal(next.settings!.content, previous.settings!.content);
    assert.equal(library.detail('finance-expert').name, '验收财研');
    assert.equal(library.detail('finance-expert').defaultModel, '用户模型偏好');
    assert.equal(fs.readFileSync(path.join(root, 'expert-packs/finance-expert/soul.md'), 'utf8'), sourceSoul);
    assert.equal(fs.readFileSync(path.join(root, 'expert-packs/finance-expert/memory/MEMORY.md'), 'utf8'), sourceMemory);
    assert.equal(fs.readFileSync(path.join(root, 'expert-packs/finance-expert/skills/skill-index.yaml'), 'utf8'), sourceIndex);
    library.removeExpert('finance-expert'); assert.throws(() => store.read('finance-expert'), /已移除/);
    library.restoreExperts(); assert.equal(store.read('finance-expert').versions.length, previous.versions.length);
  });
  const report = { ok: true, platform: process.platform, arch: process.arch, versions: process.versions, checks };
  fs.mkdirSync(path.dirname(output), { recursive: true }); fs.writeFileSync(output, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { store.close(); library.close(); fs.rmSync(profile, { recursive: true, force: true }); }
